// ---------------------------------------------------------------------------
// `DeriveKeyPair` agreement.
//
// Two conformant implementations must produce identical key pairs from the same
// IKM: RFC 9180 §7.1.3 fixes it for the DHKEMs, and draft-ietf-hpke-pq §3.2/§4.2
// fixes it for ML-KEM and the hybrids via
// `SHAKE256.LabeledDerive(ikm, "DeriveKeyPair", "", Nsk)`.
//
// The PQ rows are the only check that hpke-ng's `LabeledDerive` byte layout
// (draft-ietf-hpke-hpke §4: `ikm || "HPKE-v1" || suite_id ||
// lengthPrefixed(label) || I2OSP(L, 2) || context`) is right — no published
// DeriveKeyPair vectors exist for these KEMs, so agreement with an independent
// implementation is the available oracle. `tests/kat_xwing.rs` pins the X-Wing
// primitive itself against the draft's own vectors.
// ---------------------------------------------------------------------------

macro_rules! diff_rh_derive_key_pair {
	($name:ident, $ng_kem:ty, $rh_kem:ty, $seed:expr) => {
		#[test]
		fn $name() {
			let mut prng = ChaCha20Rng::seed_from_u64($seed);
			for iter in 0..ITERATIONS {
				// 64 bytes is safe for every Nsk here (P-521 needs 66 bits of
				// rejection sampling input but accepts any IKM length).
				let mut ikm = vec![0u8; 64];
				prng.fill_bytes(&mut ikm);

				let (_, ng_pk) = <$ng_kem as ng::Kem>::derive_key_pair(&ikm).unwrap();
				let (_, rh_pk) = <$rh_kem as RhKem>::derive_keypair(&ikm);
				assert_eq!(
					ng_pk.as_ref(),
					&rh_pk.to_bytes()[..],
					"DeriveKeyPair diverged (iter {iter})",
				);
			}
		}
	};
}

