//! Cross-implementation differential test against `rust-hpke` (rozbb/hpke).
//!
//! `tests/differential.rs` compares against `hpke-rs`, whose RustCrypto backend
//! supports only X25519, P-256 and secp256k1. This file covers the KEMs that
//! had no independent validation at all — P-384, ML-KEM-768, ML-KEM-1024 and
//! X-Wing — plus X25519 and P-256 as controls proving the harness itself is
//! sound, and P-521 which previously had KAT coverage but no cross-check.
//!
//! Unlike the `hpke-rs` harness this needs no `hazmat-` feature: it drives both
//! libraries entirely through their public APIs. Each suite runs both
//! directions — hpke-ng seals and rust-hpke opens, then rust-hpke seals and
//! hpke-ng opens — and the two exporter secrets must agree. Between them those
//! checks pin the public-key, private-key and encapsulated-key wire formats,
//! `kem_context` construction, the key schedule, the AEAD nonce sequence, and
//! the exporter.

#![allow(non_snake_case)]

use hpke::{
	Deserializable, Kem as RhKem, OpModeR, OpModeS, Serializable, setup_receiver,
	setup_sender_with_rng,
};
use hpke_ng as ng;
use rand::{Rng, SeedableRng};
use rand_chacha::ChaCha20Rng;

const ITERATIONS: usize = 3;

/// Full bidirectional interop for one ciphersuite.
///
/// Keys are generated by hpke-ng and handed to rust-hpke as wire bytes, which
/// also asserts that both libraries serialize them identically. That works for
/// every KEM regardless of how each side implements `DeriveKeyPair`.
macro_rules! diff_rh {
	(
		$name:ident,
		$ng_kem:ty, $ng_kdf:ty, $ng_aead:ty,
		$rh_kem:ty, $rh_kdf:ty, $rh_aead:ty,
		$seed:expr
	) => {
		#[test]
		fn $name() {
			type NgSuite = ng::Hpke<$ng_kem, $ng_kdf, $ng_aead>;
			type RhPublicKey = <$rh_kem as RhKem>::PublicKey;
			type RhPrivateKey = <$rh_kem as RhKem>::PrivateKey;
			type RhEncappedKey = <$rh_kem as RhKem>::EncappedKey;

			let mut prng = ChaCha20Rng::seed_from_u64($seed);

			for iter in 0..ITERATIONS {
				let mut buf = |n: usize| {
					let mut v = vec![0u8; n];
					prng.fill_bytes(&mut v);
					v
				};
				let info = buf(16);
				let aad = buf(16);
				let pt = buf(64);

				// --- Keys: generated by hpke-ng, loaded by rust-hpke ---------
				let (ng_sk, ng_pk) = <$ng_kem as ng::Kem>::generate(&mut prng).unwrap();
				let pk_bytes = ng_pk.as_ref().to_vec();
				let sk_bytes = <$ng_kem as ng::Kem>::sk_to_bytes(&ng_sk);

				let rh_pk = RhPublicKey::from_bytes(&pk_bytes)
					.expect("rust-hpke rejected an hpke-ng public key");
				let rh_sk = RhPrivateKey::from_bytes(&sk_bytes)
					.expect("rust-hpke rejected an hpke-ng private key");
				assert_eq!(
					&rh_pk.to_bytes()[..],
					pk_bytes.as_slice(),
					"public key serialization diverged (iter {iter})",
				);
				assert_eq!(
					&rh_sk.to_bytes()[..],
					sk_bytes.as_slice(),
					"private key serialization diverged (iter {iter})",
				);

				// --- Direction A: hpke-ng seals, rust-hpke opens -------------
				let (ng_enc, ng_ct) =
					NgSuite::seal_base(&mut prng, &ng_pk, &info, &aad, &pt).unwrap();
				let rh_enc = RhEncappedKey::from_bytes(ng_enc.as_ref())
					.expect("rust-hpke rejected an hpke-ng encapsulated key");
				let mut rh_recv = setup_receiver::<$rh_aead, $rh_kdf, $rh_kem>(
					&OpModeR::Base,
					&rh_sk,
					&rh_enc,
					&info,
				)
				.expect("rust-hpke setup_receiver");
				assert_eq!(
					rh_recv
						.open(&ng_ct, &aad)
						.expect("rust-hpke could not open"),
					pt,
					"rust-hpke open of hpke-ng ciphertext (iter {iter})",
				);

				// --- Direction B: rust-hpke seals, hpke-ng opens -------------
				let (rh_enc2, mut rh_send) = setup_sender_with_rng::<$rh_aead, $rh_kdf, $rh_kem>(
					&OpModeS::Base,
					&rh_pk,
					&info,
					&mut prng,
				)
				.expect("rust-hpke setup_sender");
				let rh_ct = rh_send.seal(&pt, &aad).expect("rust-hpke seal");

				let ng_enc2 = <$ng_kem as ng::Kem>::enc_from_bytes(&rh_enc2.to_bytes()[..])
					.expect("hpke-ng rejected a rust-hpke encapsulated key");
				assert_eq!(
					NgSuite::open_base(&ng_enc2, &ng_sk, &info, &aad, &rh_ct)
						.expect("hpke-ng could not open"),
					pt,
					"hpke-ng open of rust-hpke ciphertext (iter {iter})",
				);

				// --- Exporter agreement on the shared context ----------------
				// Sender and receiver derive the same exporter secret, so the
				// rust-hpke sender context and the hpke-ng receiver context
				// must export identical values.
				let ng_recv = NgSuite::setup_receiver_base(&ng_enc2, &ng_sk, &info).unwrap();
				for &l in &[16usize, 32, 64] {
					let mut rh_out = vec![0u8; l];
					rh_send
						.export(b"diff-export", &mut rh_out)
						.expect("rust-hpke export");
					assert_eq!(
						ng_recv.export(b"diff-export", l).unwrap(),
						rh_out,
						"export len={l} diverged (iter {iter})",
					);
				}
			}
		}
	};
}

